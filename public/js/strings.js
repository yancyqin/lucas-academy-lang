export const strings = {zh, en};
export const storyStrings = {zh: storyZh, en: storyEn};
let language = 'zh';
let kind = 'scripture';

export function setLanguage(value) {
  language = value === 'en' ? 'en' : 'zh';
  document.documentElement.lang = language === 'en' ? 'en' : 'zh-CN';
}

// The kind of lesson in hand: a story, or a lesson of poems, words its labels
// by sentence.
export function setKind(value) {
  kind = value === 'story' || value === 'poems' ? 'story' : 'scripture';
}

export const uiLanguage = () => language;

export function t(key, values = {}) {
  const entry = (kind === 'story' ? storyStrings[language][key] : undefined) ?? strings[language][key] ?? strings.zh[key];
  if (entry === undefined) return key;
  return typeof entry === 'function' ? entry(values) : entry;
}

// Lesson metadata is stored as {zh, en}; pick the interface language's form.
export const pick = value => (value && typeof value === 'object' ? value[language] ?? value.zh : value);

// Fixed page text, marked in the HTML with data-i18n (text) and
// data-i18n-aria-label / -title / -placeholder (attributes).
export function applyPage(root = document) {
  for (const node of root.querySelectorAll('[data-i18n]')) node.textContent = t(node.dataset.i18n);
  for (const [attribute, dataKey] of [['aria-label', 'i18nAriaLabel'], ['title', 'i18nTitle'], ['placeholder', 'i18nPlaceholder']]) {
    for (const node of root.querySelectorAll(`[data-${attribute === 'aria-label' ? 'i18n-aria-label' : 'i18n-' + attribute}]`)) {
      node.setAttribute(attribute, t(node.dataset[dataKey]));
    }
  }
  document.title = `${t('name')} · ${t('tagline')}`;
}
